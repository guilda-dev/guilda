(function (root) {
  'use strict';

  const SUPPORTED_INDEX_VERSION = 5;
  const SUPPORTED_CLASS_VERSION = 5;
  const pendingLoads = new Map();
  const loaderScriptUrl = document.currentScript?.src || root.location.href;
  const documentationRootUrl = new URL('.', loaderScriptUrl);

  function schemaVersion(value) {
    const version = Number(value?.schema?.version ?? 0);
    return Number.isFinite(version) ? version : 0;
  }

  function validateIndex(index) {
    if (!index || !Array.isArray(index.classes)) {
      throw new Error('The documentation class index is invalid.');
    }
    const version = schemaVersion(index);
    if (version > SUPPORTED_INDEX_VERSION) {
      throw new Error(`Unsupported class index schema version: ${version}`);
    }
    return index;
  }

  function validateClassDocument(className, data) {
    if (!data || data.ClassName !== className) {
      throw new Error(`Class data was not registered: ${className}`);
    }
    const version = schemaVersion(data);
    if (version > SUPPORTED_CLASS_VERSION) {
      throw new Error(`Unsupported class document schema version: ${version}`);
    }
    return data;
  }

  // database/list_Classes.js is generated by GUILDA.doc and is not in git.
  // Without it the pages show an empty reference with build instructions.
  const EMPTY_INDEX = Object.freeze({
    schema: { name: 'GUILDA documentation class index (missing)', version: 0, classDocumentVersion: 0 },
    classes: []
  });

  function hasIndex() {
    return Boolean(root.GUILDA_DOC_INDEX && Array.isArray(root.GUILDA_DOC_INDEX.classes));
  }

  function getIndex() {
    return hasIndex() ? validateIndex(root.GUILDA_DOC_INDEX) : EMPTY_INDEX;
  }

  function getClasses() {
    return getIndex().classes;
  }

  function getRouteParams() {
    const queryParams = new URLSearchParams(root.location.search || '');
    const hashText = (root.location.hash || '').replace(/^#/, '');
    const hashParams = new URLSearchParams(hashText);
    return {
      get: (name) => queryParams.get(name) || hashParams.get(name)
    };
  }

  function pageUrl(pageName, params) {
    const currentPageUrl = root.location.href.split(/[?#]/)[0];
    const targetUrl = new URL(pageName, currentPageUrl);
    if (typeof params === 'string') {
      targetUrl.hash = params;
    } else if (params && typeof params === 'object') {
      targetUrl.hash = new URLSearchParams(params).toString();
    }
    return targetUrl.href;
  }

  function navigate(pageName, params) {
    root.location.assign(pageUrl(pageName, params));
  }

  function findClass(className) {
    const target = (className || '').toLowerCase();
    return getClasses().find((item) => (item.Name || item.name || '').toLowerCase() === target) || null;
  }

  function parentNames(meta) {
    if (Array.isArray(meta?.Superclasses)) return meta.Superclasses;
    return (meta?.Parent || '').split(',').map((name) => name.trim()).filter(Boolean);
  }

  // Schema v5 lists the direct subclasses; v4 derives them from the parents.
  function getSubclasses(className) {
    const meta = findClass(className);
    if (Array.isArray(meta?.Subclasses)) {
      return meta.Subclasses.map((name) => findClass(name) || { Name: name });
    }
    return getClasses().filter((item) => parentNames(item).includes(className));
  }

  // Root folders of the source tree and the name shown for each one.
  const ROOT_NAMES = { _GUILDAsystem: 'System', _GUILDAobject: 'Object' };

  // Schema v4 has no folder tree: build one from the class files. It holds
  // the classdef files only, since v4 does not list method files.
  function treeFromClassFiles(classes) {
    const roots = [];
    const folderOf = new Map();
    const folder = (path, name, siblings) => {
      if (!folderOf.has(path)) {
        const node = { Name: name, Kind: 'folder', Path: path, Children: [] };
        folderOf.set(path, node);
        siblings.push(node);
      }
      return folderOf.get(path);
    };
    classes.forEach((meta) => {
      const parts = (meta.File || '').replace(/\\/g, '/').split('/').filter(Boolean);
      if (parts.length < 2) return;
      let siblings = roots;
      let path = '';
      parts.slice(0, -1).forEach((part, index) => {
        path = path ? `${path}/${part}` : part;
        siblings = folder(path, index === 0 ? (ROOT_NAMES[part] || part) : part, siblings).Children;
      });
      siblings.push({ Name: parts[parts.length - 1], Kind: 'file', Path: parts.join('/'), Class: meta.Name, Children: [] });
    });
    const sortNodes = (nodes) => {
      nodes.sort((a, b) => ((a.Kind === 'file') - (b.Kind === 'file')) || a.Name.localeCompare(b.Name));
      nodes.forEach((node) => sortNodes(node.Children));
    };
    roots.forEach((root) => sortNodes(root.Children));
    return roots;
  }

  let derivedTree = null;
  function getTree() {
    const index = getIndex();
    if (Array.isArray(index.tree)) return index.tree;
    if (!derivedTree) derivedTree = treeFromClassFiles(index.classes);
    return derivedTree;
  }

  function normalizeClassPath(path) {
    const normalized = (path || '').replace(/\\/g, '/');
    const databasePosition = normalized.toLowerCase().lastIndexOf('/database/');
    if (databasePosition >= 0) return `.${normalized.slice(databasePosition)}`;
    if (normalized.startsWith('database/')) return `./${normalized}`;
    return normalized;
  }

  function resolveClassPath(className) {
    const meta = findClass(className);
    if (!meta) return '';
    const relativePath = normalizeClassPath(meta.path);
    if (relativePath) {
      return new URL(relativePath.replace(/^\.\//, ''), documentationRootUrl).href;
    }
    // Fallback when the index has no path: database/<folder>/<Class>.js.
    const originFolder = { System: 'GUILDAsystem', Object: 'GUILDAobject', User: 'User' }[meta.Origin];
    if (originFolder) {
      return new URL(`database/${originFolder}/${meta.Name}.js`, documentationRootUrl).href;
    }
    return '';
  }

  function registeredClass(className) {
    return root.GUILDA_DOC_CLASSES?.[className] || null;
  }

  function loadClass(className) {
    const cached = registeredClass(className);
    if (cached) {
      return Promise.resolve({
        meta: findClass(className),
        data: validateClassDocument(className, cached)
      });
    }
    if (pendingLoads.has(className)) return pendingLoads.get(className);

    const meta = findClass(className);
    const path = resolveClassPath(className);
    if (!meta || !path) {
      return Promise.reject(new Error(`Class metadata was not found: ${className}`));
    }

    const promise = new Promise((resolve, reject) => {
      const script = document.createElement('script');
      script.src = path;
      script.onload = () => {
        try {
          resolve({ meta, data: validateClassDocument(className, registeredClass(className)) });
        } catch (error) {
          reject(error);
        }
      };
      script.onerror = () => reject(new Error(`Class data could not be loaded: ${path}`));
      document.head.appendChild(script);
    }).finally(() => pendingLoads.delete(className));

    pendingLoads.set(className, promise);
    return promise;
  }

  root.GuildaDocLoader = Object.freeze({
    hasIndex,
    getIndex,
    getSchema: () => getIndex().schema,
    getValidation: () => getIndex().validation || { warningCount: 0, errorCount: 0, classes: [] },
    getCoverage: () => getIndex().coverage || null,
    getClasses,
    parentNames,
    getSubclasses,
    getTree,
    getRouteParams,
    pageUrl,
    navigate,
    findClass,
    resolveClassPath,
    loadClass
  });
})(window);
