function sct_ctl = control_list(obj)
% Controls of the panel of show_controls: the drawing, colors, sizes, flow and labels.
%
% Dimension, the quantities of the colors, widths, sizes and heights, and the ranges can
% be changed in 2D and 3D (the heights work in both). FlowAnimation and FlowSpeed act on
% the dots of 2D only, so they are disabled in 3D; FlowMode stays enabled (the cones of
% 3D follow its direction). ColorLimits has an Auto checkbox ([NaN NaN]: limits from the
% data); while it is checked the spinners show the limits in use (the CLim of the axes).
% The time is in the playback bar. See GraphBase.control_list for the fields.
    arguments (Input)
        obj
    end
    arguments (Output)
        sct_ctl struct  % Controls of the panel, one row each.
    end
    fcn_2d = @(G) G.Dimension == "2D";
    sct_ctl = struct( ...
        "Property",  {"Dimension", "BusHeightMode", ...
                      "ColorMode", "ColorLimits", ...
                      "BranchWidthMode", "BranchWidthRange", "MarkerSizeMode", "MarkerSizeRange", "LinkWidth", ...
                      "FlowMode", "FlowAnimation", "FlowSpeed", ...
                      "LabelMode", "LabelFontSize"}, ...
        "Widget",    {"dropdown", "dropdown", ...
                      "dropdown", "range", ...
                      "dropdown", "range", "dropdown", "range", "spinner", ...
                      "dropdown", "toggle", "slider", ...
                      "dropdown", "spinner"}, ...
        "Items",     {["2D" "3D"], ["none" "V" "angle" "Vimag" "P" "Q"], ...
                      ["none" "Loss" "I" "P" "Q" "user"], @(G) G.ax(1).CLim, ...
                      ["none" "P" "Q" "I" "G" "B" "Y" "Ysvd"], [], ["none" "P" "Q" "S"], [], [], ...
                      ["none" "P" "Q" "I"], [], [], ...
                      ["none" "bus" "tag" "value" "user"], []}, ...
        "Limits",    {[], [], ...
                      [], [], ...
                      [], [0.5 20], [], [1 30], [0.5 10], ...
                      [], [], [0.1 5], ...
                      [], [3 20]}, ...
        "Step",      {[], [], ...
                      [], 0.1, ...
                      [], 0.5, [], 0.5, 0.5, ...
                      [], [], [], ...
                      [], 1}, ...
        "Label",     {"Drawing", "Bus height", ...
                      "Color", "Color limits", ...
                      "Branch width", "Width range [pt]", "Marker size", "Size range [pt]", "Link width [pt]", ...
                      "Flow", "Animate the flow", "Flow speed", ...
                      "Labels", "Font size"}, ...
        "Group",     {"View", "View", ...
                      "Color", "Color", ...
                      "Size", "Size", "Size", "Size", "Size", ...
                      "Flow", "Flow", "Flow", ...
                      "Label", "Label"}, ...
        "EnableFcn", {[], [], ...
                      [], [], ...
                      [], [], [], [], [], ...
                      [], fcn_2d, fcn_2d, ...
                      [], []});
end
