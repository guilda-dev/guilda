function sct_map = style_properties(obj) %#ok<MANU>
% Options of set_style for each kind of element and the vector property each one writes.
    arguments (Input)
        obj
    end
    arguments (Output)
        sct_map (1,1) struct  % Kind -> option -> property name.
    end
    sct_map = struct( ...
        "line",   struct("Color", "SeriesColor", "Label", "SeriesLabel", "LineWidth", "SeriesLineWidth", ...
                         "LineStyle", "SeriesLineStyle", "Marker", "SeriesMarker", ...
                         "MarkerSize", "SeriesMarkerSize", "Visible", "SeriesVisible"), ...
        "marker", struct("Color", "SeriesColor", "Label", "SeriesLabel", "Marker", "SeriesMarker", ...
                         "MarkerSize", "SeriesMarkerSize", "Visible", "SeriesVisible"), ...
        "bar",    struct("Color", "SeriesColor", "Visible", "SeriesVisible"));
end
