        "Limits",   {[], [], [], [0 1], [0 2], [0 2]}, ...
        "Step",     {[], [], [], [], 0.05, 0.05}, ...
        "Label",    {"Labels", "Values of P and Iq", "Legend", "Rotation shown", "Arrow scale P", "Arrow scale Iq"}, ...
        "Group",    {"Label", "Label", "Label", "View", "View", "View"});
end
