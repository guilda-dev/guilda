    arguments (Output)
        sct_ctl struct  % Controls of the panel, one row each.
    end
    sct_ctl = struct( ...
        "Property", {"ShowLabel", "ShowValue", "ShowLegend", "RotationScale", "ArrowScaleP", "ArrowScaleQ"}, ...
