function sct_ctl = control_list(obj) %#ok<MANU>
% Controls of the panel of show_controls: Display, ColorLimits and Tolerance.
%
% ColorLimits has an Auto checkbox ([NaN NaN]: limits over all samples); while it is
% checked the spinners show the limits in use (the CLim of the axes). It is disabled for
% "pattern", which has no colors. The time is in the playback bar. See
% GraphBase.control_list for the fields.
    arguments (Input)
        obj
    end
    arguments (Output)
        sct_ctl struct  % Controls of the panel, one row each.
    end
    sct_ctl = struct( ...
        "Property",  {"Display", "ColorLimits", "Tolerance"}, ...
        "Widget",    {"dropdown", "range", "spinner"}, ...
        "Items",     {["pattern" "magnitude" "value"], @(G) G.ax(1).CLim, []}, ...
        "Limits",    {[], [], [0 Inf]}, ...
        "Step",      {[], 0.1, []}, ...
        "Label",     {"Display", "Color limits", "Tolerance"}, ...
        "Group",     {"View", "Color", "View"}, ...
        "EnableFcn", {[], @(G) G.Display ~= "pattern", []});
end
