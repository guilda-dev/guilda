function h = draw_sphere(ax, x0, y0, z0, radius, color)
arguments (Input)
    ax      % Axes to draw in.
    x0      % X coordinate of the center.
    y0      % Y coordinate of the center.
    z0      % Z coordinate of the center.
    radius  % Size of the solid.
    color   % Face color.
end
arguments (Output)
    h       % Surface drawn.
end
[xs, ys, zs] = sphere(14);
h = surf(ax, ...
    x0 + radius*xs, ...
    y0 + radius*ys, ...
    z0 + radius*zs, ...
    'FaceColor', color, ...
    'EdgeColor', 'none', ...
    'AmbientStrength', 0.20, ...
    'DiffuseStrength', 0.68, ...
    'SpecularStrength', 0.92, ...
    'SpecularExponent', 36, ...
    'BackFaceLighting', 'reverselit', ...
    'HandleVisibility', 'off');
end
